const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    try {
      return localStorage.getItem("boutique_language") || "en";
    } catch {
      return "en";
    }
  });

  const setLang = useCallback((nextLang) => {
    if (TRANSLATIONS[nextLang]) {
      setLangState(nextLang);
      try {
        localStorage.setItem("boutique_language", nextLang);
        document.documentElement.lang = nextLang;
      } catch (err) {
        console.warn("Could not save language preference:", err);
      }
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  // Translation helper function
  const t = useCallback(
    (key, fallback = "") => {
      const currentDict = TRANSLATIONS[lang] || TRANSLATIONS.en;
      if (currentDict && currentDict[key] !== undefined) {
        return currentDict[key];
      }
      const englishDict = TRANSLATIONS.en;
      if (englishDict && englishDict[key] !== undefined) {
        return englishDict[key];
      }
      return fallback || key;
    },
    [lang]
  );

  const currentLanguage = LANGUAGES.find((l) => l.code === lang) || LANGUAGES[0];

  const value = useMemo(
    () => ({
      lang,
      setLang,
      t,
      languages: LANGUAGES,
      currentLanguage: LANGUAGES.find((l) => l.code === lang) || LANGUAGES[0],
      isEthiopic: lang === "am" || lang === "ti",
    }),
    [lang, setLang, t]
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used within a LanguageProvider");
  }
  return context;
};

